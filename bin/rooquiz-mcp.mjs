#!/usr/bin/env node
/**
 * stdio ↔ Streamable HTTP bridge for the hosted RooQuiz MCP server.
 *
 * The server itself runs at https://payload.rooquiz.com/api/mcp and speaks Streamable
 * HTTP. Clients that only support stdio (Claude Desktop, older MCP hosts) and registry
 * crawlers that build a container and pipe JSON-RPC over stdin/stdout need this shim.
 * Clients with native HTTP support (Claude Code, Cursor, VS Code, claude.ai, ChatGPT)
 * should point at the URL directly — see the README.
 *
 * No dependencies on purpose: Node >= 18 built-ins only, so the container is one COPY
 * and there is no supply chain to audit.
 *
 * Env:
 *   ROOQUIZ_TOKEN    bearer token. Set it and every message is forwarded upstream, which
 *                    is the only way to actually call a tool. Without a usable one the
 *                    bridge still completes a handshake — see the introspection note below.
 */

import { readFileSync } from 'node:fs'

const ENDPOINT = 'https://payload.rooquiz.com/api/mcp'
const TOKEN = process.env.ROOQUIZ_TOKEN || ''

// JSON-RPC 2.0 error codes we synthesize locally (the server owns the rest).
const ERR_PARSE = -32700
const ERR_INTERNAL = -32603
// What the hosted server answers with when the bearer token is missing, wrong, or revoked.
const ERR_UNAUTHORIZED = -32001

/**
 * Snapshot of what the hosted server answers `initialize` and `tools/list` with,
 * regenerated by scripts/snapshot-tools.mjs.
 *
 * The server requires a bearer token on every method, `initialize` included — correct
 * behaviour for an OAuth-protected resource (the 401 carries the `WWW-Authenticate`
 * header clients use to discover the authorization server, so it must not be relaxed).
 * But registry crawlers build this container, pipe JSON-RPC in, and judge the server by
 * whether it introspects. Handshake and tool list are public information, so we answer
 * those two from the snapshot rather than fail the handshake.
 *
 * "No credentials" is not only an empty token: Glama fills every declared env var with a
 * placeholder (`roq_pat_dummy_...`), so the crawler always arrives holding something that
 * looks like a token and 401s. Both routes therefore land here — an unset token skips the
 * round trip, an unusable one falls back after upstream refuses it.
 *
 * A working token never reads this file: the fallback is only reachable through a 401, so
 * a stale snapshot can never shadow live data. `tools/call` has no local answer either
 * way, so a bad token still surfaces its 401 where the operator will notice it.
 */
let snapshotCache = null

function loadSnapshot() {
  if (snapshotCache) {
    return snapshotCache
  }
  try {
    snapshotCache = JSON.parse(readFileSync(new URL('./introspection.json', import.meta.url), 'utf8'))
  } catch {
    // Someone copied the .mjs out on its own. Degrade to an empty-but-valid handshake
    // rather than crashing the process on startup.
    snapshotCache = {
      protocolVersions: ['2025-11-25'],
      serverInfo: { name: 'rooquiz-mcp', version: '0.0.0' },
      capabilities: { tools: {} },
      tools: [],
    }
  }
  return snapshotCache
}

/**
 * stdout writes must not interleave — every message goes through here.
 *
 * Writes to a pipe are asynchronous and buffered: the tokenless tools/list response is a
 * few hundred KB, far past the ~64KB a pipe holds, so exiting when the last request
 * resolves would cut the JSON mid-string. Pending writes are counted and the process only
 * leaves once they have all flushed.
 */
function send(message) {
  pendingWrites += 1
  process.stdout.write(JSON.stringify(message) + '\n', () => {
    pendingWrites -= 1
    exitWhenDrained()
  })
}

function errorResponse(id, code, message) {
  return { jsonrpc: '2.0', id: id ?? null, error: { code, message } }
}

function resultResponse(id, value) {
  return { jsonrpc: '2.0', id, result: value }
}

/** Mirrors the server: echo the client's version when we support it, else offer our latest. */
function negotiateProtocolVersion(requested, supported) {
  return typeof requested === 'string' && supported.includes(requested) ? requested : supported[0]
}

/**
 * Answers the tokenless introspection methods, or null to let the message go upstream.
 * `tools/call` deliberately falls through: without a token it must 401 so the operator
 * finds out they need one, rather than looking connected and failing later.
 */
function answerLocally(message) {
  const snapshot = loadSnapshot()

  switch (message.method) {
    case 'initialize':
      return resultResponse(message.id, {
        protocolVersion: negotiateProtocolVersion(
          message.params?.protocolVersion,
          snapshot.protocolVersions
        ),
        capabilities: snapshot.capabilities,
        serverInfo: snapshot.serverInfo,
        instructions: snapshot.instructions,
      })

    case 'ping':
      return resultResponse(message.id, {})

    case 'tools/list':
      // The server does not paginate tools/list, so there is no cursor to honour.
      return resultResponse(message.id, { tools: snapshot.tools })

    default:
      return null
  }
}

/**
 * Stamps the request's id onto the response.
 *
 * The server's 401 body carries `id: null` whatever the request asked for, and a reply
 * whose id does not match is unroutable: strict clients reject it against the JSON-RPC
 * schema (`id` must be a string or a number on a response) and then sit waiting for the
 * answer to their own id until they time out. Relaying it verbatim turns a one-line auth
 * error into a minute-long hang and, for a registry crawler, a failed build.
 */
function reconcileId(message, body) {
  if (body && typeof body === 'object' && !Array.isArray(body) && body.id !== message.id) {
    return { ...body, id: message.id ?? null }
  }
  return body
}

/** The upstream turned the message away because the token is missing, wrong, or revoked. */
function isAuthFailure(status, body) {
  return status === 401 || status === 403 || body?.error?.code === ERR_UNAUTHORIZED
}

/**
 * POSTs one message upstream. Returns the HTTP status next to the body because the caller
 * has to tell an auth refusal apart from an ordinary error response.
 */
async function forward(message) {
  const headers = {
    'Content-Type': 'application/json',
    // Streamable HTTP servers may answer with either; ours always returns JSON.
    Accept: 'application/json, text/event-stream',
  }
  if (TOKEN) {
    headers.Authorization = `Bearer ${TOKEN}`
  }

  const response = await fetch(ENDPOINT, {
    method: 'POST',
    headers,
    body: JSON.stringify(message),
  })

  // 204 (notification ack) and empty bodies carry nothing to relay.
  if (response.status === 204) {
    return { status: response.status, body: null }
  }
  const text = await response.text()
  if (!text) {
    return { status: response.status, body: null }
  }

  let body
  try {
    body = JSON.parse(text)
  } catch {
    // Non-JSON body (proxy error page, WAF block). Surface it as a JSON-RPC error
    // instead of letting the client hang waiting for a response to its id.
    body = errorResponse(
      message.id,
      ERR_INTERNAL,
      `Upstream returned HTTP ${response.status} with a non-JSON body`
    )
  }
  return { status: response.status, body: reconcileId(message, body) }
}

async function handle(line) {
  let message
  try {
    message = JSON.parse(line)
  } catch {
    send(errorResponse(null, ERR_PARSE, 'Invalid JSON'))
    return
  }

  const isNotification = message.id === undefined || message.id === null

  if (!TOKEN) {
    // Nothing upstream will accept, so spending a round trip on a notification only to
    // read a 401 nobody sees is pure noise. `notifications/initialized` lands here.
    if (isNotification) {
      return
    }
    const local = answerLocally(message)
    if (local) {
      send(local)
      return
    }
  }

  try {
    const { status, body } = await forward(message)
    // Notifications get no reply even if the server answered with a body.
    if (isNotification) {
      return
    }
    // The token upstream just refused buys no more than no token at all, so answer the
    // public methods from the snapshot rather than fail the handshake over it.
    if (isAuthFailure(status, body)) {
      const local = answerLocally(message)
      if (local) {
        send(local)
        return
      }
    }
    if (body) {
      send(body)
    }
  } catch (error) {
    if (!isNotification) {
      send(errorResponse(message.id, ERR_INTERNAL, `Request to ${ENDPOINT} failed: ${error.message}`))
    }
  }
}

/**
 * Requests are forwarded concurrently (MCP allows it), so stdin closing does not mean
 * the work is done — exiting there would drop replies for anything still in flight.
 * That is exactly what a `printf ... | rooquiz-mcp` probe does.
 */
const inFlight = new Set()
let pendingWrites = 0
let stdinEnded = false

function exitWhenDrained() {
  if (stdinEnded && inFlight.size === 0 && pendingWrites === 0) {
    process.exit(0)
  }
}

function track(promise) {
  inFlight.add(promise)
  promise.finally(() => {
    inFlight.delete(promise)
    exitWhenDrained()
  })
}

// MCP stdio framing is newline-delimited JSON (no Content-Length headers).
let buffer = ''
process.stdin.setEncoding('utf8')
process.stdin.on('data', chunk => {
  buffer += chunk
  let newline
  while ((newline = buffer.indexOf('\n')) !== -1) {
    const line = buffer.slice(0, newline).trim()
    buffer = buffer.slice(newline + 1)
    if (line) {
      track(handle(line))
    }
  }
})
process.stdin.on('end', () => {
  stdinEnded = true
  exitWhenDrained()
})
